def extract_text_content(content) -> str:
    """Extract plain text across string, list-of-dicts, or mixed content blocks."""
    if isinstance(content, str):
        return content
    elif isinstance(content, list):
        text_parts = []
        for block in content:
            if isinstance(block, str):
                text_parts.append(block)
            elif isinstance(block, dict) and block.get("type") == "text":
                text_parts.append(block.get("text", ""))
        return "".join(text_parts)
    return str(content)


def reasoning_node(state: AgentState):
    raw_messages = state["messages"]

    # (Your message order validation for Gemini goes here)
    response = llm_with_tools.invoke(raw_messages)

    # Normalize Gemini's list-of-blocks content to a standard string
    if isinstance(response.content, list):
        response.content = extract_text_content(response.content)

    return {"messages": [response]}

